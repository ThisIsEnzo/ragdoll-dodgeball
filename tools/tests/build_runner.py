#!/usr/bin/env python3
"""Build a self-contained Luau test runner with real shared modules embedded.

Luau CLI modules are sandboxed and do not share globals with the caller. Embedding
source lets the test runner compile each module into an environment inheriting the
Roblox API shims, without modifying production modules.
"""
from __future__ import annotations

import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MODULES = (
    "BalanceConfig",
    "Loadout",
    "RankCatalog",
    "ShopCatalog",
    "MonetizationCatalog",
    "AudioCatalog",
    "ContactForce",
)


def long_string(value: str) -> str:
    level = 0
    while True:
        equals = "=" * level
        closing = "]" + equals + "]"
        if closing not in value:
            return "[" + equals + "[" + value + closing
        level += 1


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", required=True, type=Path)
    args = parser.parse_args()

    entries = []
    for name in MODULES:
        path = ROOT / "src" / "shared" / (name + ".lua")
        if not path.is_file():
            raise SystemExit(f"Required test module not found: {path.relative_to(ROOT)}")
        source = path.read_text(encoding="utf-8")
        entries.append(f'    ["{name}"] = {long_string(source)},')

    runner_path = ROOT / "tools" / "tests" / "run.lua"
    runner = runner_path.read_text(encoding="utf-8")
    output = (
        "-- Generated by tools/tests/build_runner.py; do not edit.\n"
        "local TEST_MODULE_SOURCES = {\n"
        + "\n".join(entries)
        + "\n}\n\n"
        + runner
    )
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(output, encoding="utf-8")
    print(f"Embedded {len(MODULES)} production modules into {args.output}")


if __name__ == "__main__":
    main()
